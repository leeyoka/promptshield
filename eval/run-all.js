// Runs every evaluation and writes docs/METRICS.md. Nothing in METRICS.md is typed by hand.
'use strict';
const fs = require('fs');
const path = require('path');

const sections = [
  require('./run-detection-eval.js').run(),
  require('./run-restore-eval.js').run(),
  require('./run-advisor-eval.js').run(),
  require('./run-latency-bench.js').run()
];

const header = `# PromptShield metrics

Generated by \`npm run eval\` on ${new Date().toISOString()}. Do not edit by hand; re-run the script.

**How to read this honestly**
- The synthetic detection set is produced by our own seeded generator, and the rules were adjusted after
  looking at its errors. It shows the rules behave as designed; it is **not** an independent accuracy claim.
- Independent numbers come only from \`eval/dataset/heldout/\`, written by a teammate who has not seen the rules.
- The advisor development set was labelled by the rule author and the point weights were tuned on it.
- Energy figures in the product are estimates from stated assumptions (\`docs/ENERGY_ASSUMPTIONS.md\`), not measurements.
`;

const out = [header, ...sections].join('\n\n') + '\n';
const target = path.join(__dirname, '..', 'docs', 'METRICS.md');
fs.writeFileSync(target, out);
console.log(out);
console.log(`\nWrote ${path.relative(process.cwd(), target)}`);
